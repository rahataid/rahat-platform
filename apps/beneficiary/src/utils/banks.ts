const normalizeBankName = (name: string): string =>
    name
        .toLocaleLowerCase()
        .replace(/\./g, '')
        .replace(/\bltd\b/g, 'limited')
        .replace(/\s+/g, ' ')
        .trim();

const getBankId = (bankName: string): string | null => {
    const normalized = normalizeBankName(bankName);
    const bankId = CIPS_BANK.find((bank) => normalizeBankName(bank.bankName) === normalized)?.bankId;
    return bankId || null;
}

const getBankName = (bankId: string): string | null => {
    const bankName = CIPS_BANK.find((bank) => bank.bankId.toLocaleLowerCase() === bankId.toLocaleLowerCase())?.bankName;
    return bankName || null;
}

export { getBankId, getBankName };
